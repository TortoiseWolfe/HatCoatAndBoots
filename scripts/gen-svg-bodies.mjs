import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

// Inline the inner body (everything inside <svg>...</svg>) of each chapter SVG
// into a TS module so the client viewer can render them as <g> groups in one
// shared 0 0 360 360 coordinate space (real explode, not stacked full-canvas imgs).
const BOOK = 'public/book';
const out = {};
for (const chapter of readdirSync(BOOK)) {
  const dir = join(BOOK, chapter);
  let files;
  try { files = readdirSync(dir).filter((f) => f.endsWith('.svg')); } catch { continue; }
  out[chapter] = {};
  for (const file of files) {
    const id = file.replace(/\.svg$/, '');
    const raw = readFileSync(join(dir, file), 'utf8');
    // strip the outer <svg ...> open tag and the closing </svg>, keep the body
    const body = raw
      .replace(/^[\s\S]*?<svg[^>]*>/i, '')
      .replace(/<\/svg>\s*$/i, '')
      .trim();
    out[chapter][id] = body;
  }
}

const header = `// AUTO-GENERATED by scripts/gen-svg-bodies.mjs — do not edit by hand.
// Inlined inner bodies of each chapter's layer SVGs (shared viewBox 0 0 360 360),
// so the viewer can render them as <g> groups and truly explode them.
export const SVG_BODIES: Record<string, Record<string, string>> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync('src/components/organisms/ExplodedBuilding/svg-bodies.generated.ts', header);
console.log('wrote svg-bodies.generated.ts with chapters:', Object.keys(out).map(c => `${c}(${Object.keys(out[c]).length})`).join(', '));
